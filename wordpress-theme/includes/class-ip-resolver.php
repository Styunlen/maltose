    /**
     * 解析 IP → ['country' => 国家, 'province' => 省份|null]，未命中返回 null。
     *
     * 匹配优先级：省份具体段 > 海外具体段 > 大陆 /8 粗粒度兜底。
     * 海外段必须先于大陆 /8 检查——大陆的粗粒度段（如 101.0.0.0/8）覆盖了
     * 日本/韩国/新加坡等海外细分配，若先查大陆会把海外 IP 误判为中国。
     */
    public function resolve(string $ip): ?array {
        if (filter_var($ip, FILTER_VALIDATE_IP, FILTER_FLAG_IPV4) === false) {
            return null;
        }
        // 私有 / 保留地址（RFC1918、环回、链路本地、文档段）不参与地理定位。
        if (filter_var($ip, FILTER_VALIDATE_IP, FILTER_FLAG_NO_PRIV_RANGE | FILTER_FLAG_NO_RES_RANGE) === false) {
            return null;
        }
        $long = sprintf('%u', ip2long($ip));

        foreach ($this->provinceNets() as $net => $province) {
            if ($this->inRange($long, $net)) {
                return ['country' => '中国', 'province' => $province];
            }
        }
        foreach ($this->overseasNets() as $entry) {
            [$net, $country] = explode('|', $entry, 2);
            if ($this->inRange($long, $net)) {
                return ['country' => $country, 'province' => null];
            }
        }
        foreach ($this->mainlandNets() as $net) {
            if ($this->inRange($long, $net)) {
                return ['country' => '中国', 'province' => null];
            }
        }
        return null;
    }

    /** 预解析 CIDR → [baseLong, maskLong]，只做一次。 */
    private function provinceNets(): array {
        if (self::$chinaProvinceNets === null) {
            self::$chinaProvinceNets = [];
            foreach (self::CHINA_PROVINCES as [$cidr, $province]) {
                self::$chinaProvinceNets[$this->normalize($cidr)] = $province;
            }
        }
        return self::$chinaProvinceNets;
    }

    private function mainlandNets(): array {
        if (self::$mainlandNets === null) {
            self::$mainlandNets = array_map(fn($c) => $this->normalize($c), self::CHINA_MAINLAND);
        }
        return self::$mainlandNets;
    }

    private function overseasNets(): array {
        if (self::$overseasNets === null) {
            // 按掩码长度降序（细段优先）排序，避免粗段（如 128.0.0.0/8 美国）
            // 先匹配吞掉其中的细段（如 128.112.0.0/13 韩国）。键是
            // "base/mask" 字符串，掩码越大（/13 > /8）排序越靠前。
            $items = [];
            foreach (self::OVERSEAS as [$cidr, $country]) {
                $items[] = ['net' => $this->normalize($cidr), 'country' => $country];
            }
            usort($items, function ($a, $b) {
                $mA = (int) explode('/', $a['net'])[1];
                $mB = (int) explode('/', $b['net'])[1];
                return $mB <=> $mA;
            });
            self::$overseasNets = [];
            foreach ($items as $item) {
                self::$overseasNets[] = $item['net'] . '|' . $item['country'];
            }
        }
        return self::$overseasNets;
    }

    /** CIDR → 'base/mask' 归一化键，供 inRange 复用解析结果。 */
    private function normalize(string $cidr): string {
        [$ip, $prefix] = array_pad(explode('/', $cidr), 2, '32');
        $prefix = (int) $prefix;
        $long = sprintf('%u', ip2long($ip));
        $mask = $prefix === 0 ? 0 : (0xffffffff << (32 - $prefix)) & 0xffffffff;
        $base = (int) $long & $mask;
        return $base . '/' . $mask;
    }

    private function inRange(string $long, string $normalized): bool {
        [$base, $mask] = array_pad(explode('/', $normalized), 2, '0');
        return ((int) $long & (int) $mask) === (int) $base;
    }
}
